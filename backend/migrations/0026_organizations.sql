-- Organizaciones del mundo: empresas, organismos publicos, bancos y servicios.
--
-- Una organizacion describe QUIEN opera una infraestructura. Sus maquinas, redes y
-- sitios se anadiran sobre esta raiz; no se mezcla con `clans`, que son grupos de
-- jugadores. Los comportamientos son declarativos: se guardan su codigo y configuracion,
-- pero ejecutarlos corresponde a modulos posteriores, nunca a JavaScript de una web.

CREATE TABLE organizations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(64) NOT NULL UNIQUE,
  name VARCHAR(80) NOT NULL UNIQUE,
  category VARCHAR(40) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX organizations_category_active_idx ON organizations(category, active);

-- Un comportamiento es una capacidad con nombre, por ejemplo `banking`,
-- `law-enforcement` o `search-index`. `config` deja que ese modulo reciba datos sin
-- convertir la tabla de organizaciones en una columna por comportamiento.
CREATE TABLE organization_behaviors (
  organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  code VARCHAR(60) NOT NULL,
  config JSONB NOT NULL DEFAULT '{}'::jsonb,
  PRIMARY KEY (organization_id, code)
);

CREATE INDEX organization_behaviors_code_idx ON organization_behaviors(code);
