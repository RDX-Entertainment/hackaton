-- Hardware por piezas, en vez de por columnas.
--
-- Hasta aqui una maquina era una fila de `hardware` con cuatro numeros -- cpu, ram, hdd,
-- net -- y comprar una pieza sobrescribia el numero. No habia piezas: habia niveles.
--
-- A partir de aqui hay dos objetos:
--
--   * KIT        plantilla. Que es una pieza: su tipo, su potencia, su precio y, si es una
--                placa, las compatibilidades. Las crea un administrador.
--   * COMPONENTE instancia concreta de un kit, propiedad de un jugador. Se instala en una
--                maquina, se quita, y se pone en otra. Solo puede estar en un sitio.
--
-- Lo que NO cambia es donde vive la capacidad. `hardware.cpu/ram/hdd/net` siguen siendo la
-- capacidad efectiva de la maquina, porque los tres sitios del juego que las leen lo hacen
-- ya como agregados (`SELECT sum(ram) FROM hardware WHERE user_id=...`): instalar
-- software, guardar ficheros y resolver un ataque. La diferencia es que ahora esas
-- columnas son un CALCULO -- la suma de lo instalado -- y se recalculan cada vez que una
-- pieza entra o sale. Asi el resto del juego no se entera del cambio.

-- ==============================
-- ADMINISTRADORES
-- ==============================

ALTER TABLE users ADD COLUMN is_admin BOOLEAN NOT NULL DEFAULT FALSE;

-- El catalogo lo escribe una persona, no el sistema, asi que hace falta al menos una.
-- La cuenta mas antigua queda como administrador; desde el panel se puede nombrar a otras.
UPDATE users SET is_admin = TRUE WHERE id = (SELECT min(id) FROM users);

-- ==============================
-- KITS
-- ==============================

CREATE TABLE hardware_kits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind VARCHAR(8) NOT NULL CHECK (kind IN ('cpu', 'ram', 'hdd', 'net', 'mobo')),
  name VARCHAR(40) NOT NULL,

  -- MHz, MB, MB y Mbit segun el tipo. Una placa no aporta capacidad: aporta sitio.
  power INTEGER NOT NULL DEFAULT 0 CHECK (power >= 0),
  price BIGINT NOT NULL CHECK (price >= 0),

  -- Generacion DDR. Solo significa algo en 'ram' (la que es) y en 'mobo' (la que acepta).
  -- 0 en el resto: ni la CPU ni el disco ni la red se limitan por generacion.
  generation SMALLINT NOT NULL DEFAULT 0 CHECK (generation >= 0),

  -- Ranuras. Solo significan algo en 'mobo': son el limite de piezas de cada tipo.
  cpu_slots SMALLINT NOT NULL DEFAULT 0 CHECK (cpu_slots >= 0),
  ram_slots SMALLINT NOT NULL DEFAULT 0 CHECK (ram_slots >= 0),
  hdd_slots SMALLINT NOT NULL DEFAULT 0 CHECK (hdd_slots >= 0),
  net_slots SMALLINT NOT NULL DEFAULT 0 CHECK (net_slots >= 0),

  -- Un kit retirado deja de venderse pero no rompe los componentes ya fabricados.
  listed BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX hardware_kits_kind_idx ON hardware_kits(kind, listed);

-- ==============================
-- COMPONENTES
-- ==============================

CREATE TABLE hardware_components (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kit_id BIGINT NOT NULL REFERENCES hardware_kits(id) ON DELETE RESTRICT,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  -- NULL = en el cajon, sin instalar. Que sea una sola columna es lo que garantiza que una
  -- pieza no pueda estar en dos maquinas a la vez.
  installed_in BIGINT REFERENCES hardware(server_id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX hardware_components_owner_idx ON hardware_components(user_id);
CREATE INDEX hardware_components_machine_idx ON hardware_components(installed_in);

