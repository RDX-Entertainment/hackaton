-- ==============================
-- MAQUINAS QUE YA EXISTEN
-- ==============================

-- Cada maquina de jugador se rehace en piezas equivalentes a lo que tenia: para cada
-- columna, el kit mas potente que no la supere. Asi nadie pierde capacidad y el software
-- ya instalado sigue cabiendo.
--
-- La placa se elige despues de la memoria, porque es la memoria la que fija la generacion
-- que la placa tiene que aceptar.
CREATE TEMP TABLE rebuild ON COMMIT DROP AS
SELECT
  h.server_id,
  h.user_id,
  (SELECT k.id FROM hardware_kits k WHERE k.kind = 'cpu' AND k.power <= h.cpu
     ORDER BY k.power DESC LIMIT 1) AS cpu_kit,
  (SELECT k.id FROM hardware_kits k WHERE k.kind = 'ram' AND k.power <= h.ram
     ORDER BY k.power DESC LIMIT 1) AS ram_kit,
  (SELECT k.id FROM hardware_kits k WHERE k.kind = 'hdd' AND k.power <= h.hdd
     ORDER BY k.power DESC LIMIT 1) AS hdd_kit,
  (SELECT k.id FROM hardware_kits k WHERE k.kind = 'net' AND k.power <= h.net
     ORDER BY k.power DESC LIMIT 1) AS net_kit
FROM hardware h
WHERE NOT h.is_npc;

-- La placa mas barata que acepte esa memoria y tenga sitio para todo lo demas.
ALTER TABLE rebuild ADD COLUMN mobo_kit BIGINT;

UPDATE rebuild r
SET mobo_kit = (
  SELECT k.id
  FROM hardware_kits k
  WHERE k.kind = 'mobo'
    AND k.generation = COALESCE(
      (SELECT rk.generation FROM hardware_kits rk WHERE rk.id = r.ram_kit), 2
    )
    AND k.cpu_slots >= 1 AND k.ram_slots >= 1
    AND k.hdd_slots >= 1 AND k.net_slots >= 1
  ORDER BY k.price
  LIMIT 1
);

INSERT INTO hardware_components (kit_id, user_id, installed_in)
SELECT kit, user_id, server_id
FROM rebuild, LATERAL (VALUES (mobo_kit), (cpu_kit), (ram_kit), (hdd_kit), (net_kit)) AS v(kit)
WHERE kit IS NOT NULL;

-- ==============================
-- LA CAPACIDAD PASA A SER UN CALCULO
-- ==============================

-- A partir de aqui las cuatro columnas son la suma de lo instalado. El backend las
-- recalcula con esta misma expresion cada vez que una pieza entra o sale.
UPDATE hardware h
SET cpu = COALESCE(s.cpu, 0),
    ram = COALESCE(s.ram, 0),
    hdd = COALESCE(s.hdd, 0),
    net = COALESCE(s.net, 0)
FROM (
  SELECT
    c.installed_in AS server_id,
    sum(k.power) FILTER (WHERE k.kind = 'cpu') AS cpu,
    sum(k.power) FILTER (WHERE k.kind = 'ram') AS ram,
    sum(k.power) FILTER (WHERE k.kind = 'hdd') AS hdd,
    sum(k.power) FILTER (WHERE k.kind = 'net') AS net
  FROM hardware_components c
  JOIN hardware_kits k ON k.id = c.kit_id
  WHERE c.installed_in IS NOT NULL
  GROUP BY c.installed_in
) s
WHERE h.server_id = s.server_id;
