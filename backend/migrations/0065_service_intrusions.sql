-- Normaliza sesiones anteriores sin convertir FTP en acceso completo.
UPDATE machine_accesses a SET permissions=c.granted_permissions,scope=c.max_access_scope,privilege=c.max_access_scope
FROM software_capabilities c WHERE c.code=CASE a.identity_name WHEN 'root' THEN 'cracker' WHEN 'ftp' THEN 'ftp_exploit' WHEN 'ssh' THEN 'ssh_exploit' END;

CREATE FUNCTION merge_access_permissions(previous jsonb, added jsonb) RETURNS jsonb
LANGUAGE sql IMMUTABLE AS $$
 SELECT COALESCE(jsonb_agg(DISTINCT value),'[]'::jsonb) FROM jsonb_array_elements(previous || added)
$$;

-- Una página atacada pertenece a un nodo, no a toda la flota del propietario.
CREATE TABLE node_web_content (
 server_id BIGINT PRIMARY KEY REFERENCES hardware(server_id) ON DELETE CASCADE,
 content TEXT NOT NULL,
 revision BIGINT NOT NULL DEFAULT 1,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE node_web_revisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 server_id BIGINT NOT NULL REFERENCES hardware(server_id) ON DELETE CASCADE,
 process_id BIGINT NOT NULL UNIQUE REFERENCES processes(pid) ON DELETE CASCADE,
 content TEXT NOT NULL,
 created_by BIGINT NOT NULL REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
