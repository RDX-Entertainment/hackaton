-- The external hard drive, and the software parked on it.
--
-- Actions 18, 19 and 20 move files between a player's own disk and a drive that is not on
-- the machine, which is what makes it worth having: formatting or losing the machine does
-- not touch it. Neither table survived into 0001, so all three actions had nowhere to go.
--
-- software_external.id is the id of the software it was copied from, not a new one. The
-- legacy wrote it that way on purpose: a file on the drive is the same file, parked
-- elsewhere, and that is how DOWNLOAD_XHD knows it is putting back what it took.
CREATE TABLE hardware_external (
  server_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  name VARCHAR(15) NOT NULL DEFAULT 'xhd',
  size INTEGER NOT NULL DEFAULT 100
);
CREATE INDEX hardware_external_user_idx ON hardware_external(user_id);

CREATE TABLE software_external (
  id BIGINT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  soft_name VARCHAR(50) NOT NULL,
  soft_version INTEGER NOT NULL,
  soft_size INTEGER NOT NULL,
  soft_ram INTEGER NOT NULL,
  soft_type SMALLINT NOT NULL,
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  licensed_to BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX software_external_user_idx ON software_external(user_id);

-- Every existing player gets the 100 the legacy column defaulted to. Selling larger drives
-- is the xhdItens half of the shop catalogue, which still needs a route to be reachable.
INSERT INTO hardware_external (user_id) SELECT id FROM users;
