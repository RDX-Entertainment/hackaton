-- Fase 5 de «cada máquina es un ordenador»: los clusters. Con esto el rumbo queda entero.
--
-- **Va la última a propósito, y el motivo es el orden entero de las cuatro anteriores.** Un
-- cluster *suma* recursos, y para sumarlos había que haberlos separado antes. Hasta la fase 1
-- el disco de un jugador ya era la suma de todas sus máquinas: agrupar equipos ahí no habría
-- significado nada, porque ya estaban agrupados sin que nadie lo hubiera decidido. Ahora que
-- cada equipo tiene lo suyo —disco, memoria y procesador—, juntarlos vuelve a ser una decisión
-- con precio.
--
-- ## El cable es la condición, el grupo es la decisión
--
-- **No se agrupa lo que no está conectado.** El cable LAN es lo físico y ya existe desde el
-- mapa de nodos; un cluster va encima y es explícito: tiene nombre y tiene **una máquina que
-- lo controla**. Dos equipos cableados no forman un cluster por estar cableados, igual que dos
-- ordenadores en la misma habitación no son uno.
--
-- Que sea explícito es lo que lo hace jugable: se ve en la pantalla, se deshace cuando el
-- jugador quiera, y cuesta pensarlo. Deducirlo del cableado habría hecho que agrupar y
-- desagrupar fuera un efecto secundario de tender un cable.
--
-- ## Si cae el controlador, el grupo se mantiene
--
-- La red queda inutilizada, pero el cluster **no se disuelve solo**. Deshacerlo es una
-- decisión del jugador, no una consecuencia de que algo se caiga: un grupo que se deshace al
-- primer golpe obligaría a rehacerlo cada vez, y eso es trámite, no juego.
--
-- Por eso el controlador se guarda como una referencia normal y no como algo que desaparezca:
-- si la máquina se da de baja hay que decir antes qué pasa con el grupo, y eso lo decide quien
-- lo montó. `ON DELETE RESTRICT`, como el software de la fase 1 y por el mismo motivo.

CREATE TABLE hardware_clusters (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           bigint  NOT NULL,
    name              varchar(15) NOT NULL,

    -- La máquina que manda. Es también miembro: un cluster sin controlador no es un grupo,
    -- es una lista.
    controller_server bigint  NOT NULL
        REFERENCES hardware(server_id) ON DELETE RESTRICT,

    created_at        timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT hardware_clusters_nombre CHECK (length(btrim(name)) > 0)
);

-- Un nombre por dueño: «cluster 1» tiene que querer decir uno solo cuando se hable de él.
CREATE UNIQUE INDEX hardware_clusters_nombre_idx
    ON hardware_clusters (user_id, lower(btrim(name)));

-- Una máquina manda en un grupo como mucho.
CREATE UNIQUE INDEX hardware_clusters_controlador_idx
    ON hardware_clusters (controller_server);

-- Y la pertenencia va en el propio equipo: es una propiedad suya, como su nombre o su
-- posición en el mapa, y así preguntar «¿de qué grupo es esta máquina?» no necesita un salto.
ALTER TABLE hardware
    ADD COLUMN cluster_id bigint
        REFERENCES hardware_clusters(id) ON DELETE SET NULL;

CREATE INDEX hardware_cluster_idx
    ON hardware (cluster_id)
    WHERE cluster_id IS NOT NULL;

COMMENT ON TABLE hardware_clusters IS
    'Grupos de equipos cableados que hacia fuera se comportan como un solo ordenador. El cable es la condicion fisica; el grupo, la decision del jugador.';
