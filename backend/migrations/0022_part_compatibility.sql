-- Compatibilidad de verdad, no solo contar ranuras.
--
-- Hasta aqui una placa decia cuantas piezas caben y que DDR acepta. Eso deja fuera lo que
-- de verdad decide si una pieza entra en un equipo:
--
--   * el TIPO      una memoria de servidor no va en una placa domestica
--   * el CHIPSET   que identifica a la placa y lo crea un administrador, no el codigo
--   * el TECHO     cuanta memoria, disco, proceso y red admite el conjunto
--
-- Las ranuras se quedan: son el limite de cuantas piezas caben. El techo es el limite de
-- cuanto suman. Son dos cosas distintas y las dos existen en una placa real: cuatro
-- zocalos de DIMM y un maximo de 128 GB no dicen lo mismo.

-- ==============================
-- CHIPSETS
-- ==============================

CREATE TABLE hardware_chipsets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(40) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO hardware_chipsets (name) VALUES
  ('A75'), ('B85'), ('Z390'), ('X670'), ('C621'), ('WRX80');

-- ==============================
-- PIEZAS
-- ==============================

ALTER TABLE hardware_parts
  -- En una placa es el tipo que impone; en el resto, el tipo que es. Instalar exige que
  -- coincidan. La lista es cerrada a proposito: los chipsets los crea un administrador,
  -- los tipos no, porque cada uno anadiria una regla de compatibilidad nueva.
  ADD COLUMN tier VARCHAR(12) NOT NULL DEFAULT 'domestica'
    CHECK (tier IN ('domestica', 'gaming', 'server', 'industrial')),

  -- Solo en placas.
  ADD COLUMN chipset_id BIGINT REFERENCES hardware_chipsets(id) ON DELETE SET NULL,
  ADD COLUMN max_cpu INTEGER NOT NULL DEFAULT 0 CHECK (max_cpu >= 0),
  ADD COLUMN max_ram INTEGER NOT NULL DEFAULT 0 CHECK (max_ram >= 0),
  ADD COLUMN max_hdd INTEGER NOT NULL DEFAULT 0 CHECK (max_hdd >= 0),
  ADD COLUMN max_net INTEGER NOT NULL DEFAULT 0 CHECK (max_net >= 0);

-- Todo lo que ya existe queda como domestico. Es lo unico que garantiza que ningun equipo
-- montado se vuelva invalido al aplicar esta migracion.
UPDATE hardware_parts SET tier = 'domestica';

-- Techos y chipset de las placas que ya estaban. Los valores son holgados respecto a lo
-- que hay instalado hoy -- la maquina mas cargada lleva 512 MB -- para que nadie se quede
-- con un equipo que la propia placa rechaza.
UPDATE hardware_parts p
SET chipset_id = c.id,
    max_cpu = v.max_cpu,
    max_ram = v.max_ram,
    max_hdd = v.max_hdd,
    max_net = v.max_net
FROM (VALUES
  ('Basic A75',  'A75',   2000,   2048,   2000,   10),
  ('Solid B85',  'B85',   3000,   8192,  10000,  100),
  ('Prime Z390', 'Z390',  4000,  32768,  40000,  500),
  ('Apex X670',  'X670',  8000, 131072, 100000, 1000)
) AS v(name, chipset, max_cpu, max_ram, max_hdd, max_net)
JOIN hardware_chipsets c ON c.name = v.chipset
WHERE p.kind = 'mobo'
  AND p.name = v.name;

