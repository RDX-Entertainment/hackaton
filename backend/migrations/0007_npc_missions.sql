CREATE TABLE npc (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  npc_type SMALLINT NOT NULL,
  npc_ip BIGINT NOT NULL UNIQUE,
  npc_pass VARCHAR(8) NOT NULL,
  down_until TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE npc_info (
  npc_id BIGINT PRIMARY KEY REFERENCES npc(id) ON DELETE CASCADE,
  name VARCHAR(50) NOT NULL,
  web TEXT NOT NULL DEFAULT ''
);
CREATE TABLE software_original (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  npc_id BIGINT NOT NULL REFERENCES npc(id) ON DELETE CASCADE,
  soft_name VARCHAR(25) NOT NULL,
  soft_version INTEGER NOT NULL,
  soft_size INTEGER NOT NULL,
  soft_ram INTEGER NOT NULL,
  soft_type SMALLINT NOT NULL,
  running BOOLEAN NOT NULL DEFAULT FALSE,
  licensed_to BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX npc_type_idx ON npc(npc_type);
