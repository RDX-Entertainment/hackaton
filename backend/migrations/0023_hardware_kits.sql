-- Kits: un equipo entero descrito como lista de piezas.
--
-- La palabra estaba reservada desde 0021, cuando lo que se llamaba `hardware_kits` paso a
-- ser `hardware_parts` porque describia piezas sueltas. Un kit es lo que de verdad
-- significa la palabra: la union de varias piezas que forman un PC montado.
--
-- No es azucar sobre la tienda. Un kit sirve para cuatro cosas distintas:
--
--   * el equipo con el que nace un jugador          (is_default)
--   * lo que una corporacion reparte a los suyos    (scope 'clan' + hardware_kit_clans)
--   * lo que se vendera en el mercado de NPCs       (scope 'marketplace')
--   * un equipo montado a la venta en la tienda     (scope 'shop')
--
-- Un kit no fabrica nada por si mismo: apunta a piezas del catalogo que ya existe. Comprar
-- uno crea un componente por cada item, igual que comprarlos de uno en uno.

-- ==============================
-- KITS
-- ==============================

CREATE TABLE hardware_kits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(40) NOT NULL UNIQUE,
  description TEXT NOT NULL DEFAULT '',
  price BIGINT NOT NULL DEFAULT 0 CHECK (price >= 0),

  -- Donde se ofrece. Una sola columna en vez de un booleano por sitio: 'marketplace only' y
  -- 'corporation only' son excluyentes por definicion, y dos booleanos permitirian marcar
  -- los dos y dejar la pregunta 'y entonces donde sale' sin respuesta.
  --
  --   shop         cualquiera lo ve en la tienda
  --   marketplace  reservado al mercado de equipos de NPC
  --   clan         solo para las corporaciones enlazadas mas abajo
  --   hidden       no se ofrece en ningun sitio; existe para aplicarlo a mano
  scope VARCHAR(12) NOT NULL DEFAULT 'shop'
    CHECK (scope IN ('shop', 'marketplace', 'clan', 'hidden')),

  -- El equipo con el que nace un jugador nuevo. Como mucho uno, y lo garantiza el indice de
  -- abajo, no la buena voluntad de quien escriba el UPDATE.
  is_default BOOLEAN NOT NULL DEFAULT FALSE,

  listed BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Un indice unico sobre una constante: solo puede entrar una fila con is_default. Hacerlo
-- en la base y no en el repositorio significa que ninguna ruta futura puede dejar dos.
CREATE UNIQUE INDEX hardware_kits_single_default ON hardware_kits ((true)) WHERE is_default;

-- ==============================
-- CONTENIDO
-- ==============================

CREATE TABLE hardware_kit_items (
  kit_id BIGINT NOT NULL REFERENCES hardware_kits(id) ON DELETE CASCADE,

  -- RESTRICT y no CASCADE: borrar una pieza del catalogo no puede vaciar un kit en
  -- silencio y dejar equipos a medio montar. Es la misma decision que en los componentes.
  part_id BIGINT NOT NULL REFERENCES hardware_parts(id) ON DELETE RESTRICT,

  amount SMALLINT NOT NULL DEFAULT 1 CHECK (amount BETWEEN 1 AND 32),
  PRIMARY KEY (kit_id, part_id)
);

-- ==============================
-- CORPORACIONES
-- ==============================

-- Un kit puede estar atado a varias corporaciones y una corporacion tener varios kits, asi
-- que la relacion es una tabla y no una columna.
--
-- La clave es el BIGINT de `clans`, que es lo que identifica a una corporacion en este
-- esquema. Meter un UUID solo aqui crearia un segundo identificador para la misma cosa.
CREATE TABLE hardware_kit_clans (
  kit_id BIGINT NOT NULL REFERENCES hardware_kits(id) ON DELETE CASCADE,
  clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
  PRIMARY KEY (kit_id, clan_id)
);

CREATE INDEX hardware_kit_clans_clan_idx ON hardware_kit_clans(clan_id);

