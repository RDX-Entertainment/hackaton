-- Las operaciones del banco dejan de vivir en la pantalla del jugador.
--
-- Hasta ahora mover dinero era algo que hacia «el dueno de la cuenta desde su pantalla»: el
-- servicio comprobaba la sesion y ademas el PIN. Eso vale para una web de banca real y no
-- para este juego, donde la gracia es justo la contraria: **quien tiene el numero de cuenta
-- y el PIN mueve el dinero**, lo haya conseguido como lo haya conseguido. Si hace falta ser
-- el dueno, robar unas credenciales no sirve de nada y no hay estafa posible.
--
-- Esta migracion trae las dos piezas que faltaban para eso:
--
--   * el rastro, para que mover dinero deje huella y el robo se pueda descubrir;
--   * los cobros, que son el gancho: se crea uno y se le pasa a alguien para que lo pague.
--
-- Un cobro sin destinatario es un enlace de pago abierto que paga cualquiera. Es la forma
-- honrada de cobrar y, con el concepto bien elegido, tambien la forma de estafar. El juego
-- no distingue: lo que cambia es a quien se lo mandes y lo que le cuentes.

-- El movimiento, visto desde una cuenta. Cada transferencia escribe dos filas —una por
-- lado— para que el extracto de cada cuenta se lea con un solo WHERE y sin OR.
CREATE TABLE bank_transactions (
    id            bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

    account       bigint NOT NULL REFERENCES bank_accounts(bank_acc) ON DELETE CASCADE,
    other_account bigint,

    -- Positivo entra, negativo sale. El signo es la direccion y no hace falta otra columna.
    amount        bigint NOT NULL CHECK (amount <> 0),

    -- Con que saldo quedo la cuenta despues. Guardarlo evita recalcular el extracto entero
    -- y deja ver el agujero aunque despues entre mas dinero.
    balance       bigint NOT NULL,

    concept       varchar(120) NOT NULL DEFAULT '',

    -- La IP desde la que se ordeno, cuando se sabe. Es lo que convierte un robo en algo
    -- investigable: la victima ve desde donde le vaciaron la cuenta.
    origin_ip     bigint,

    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX bank_transactions_account_idx ON bank_transactions(account, created_at DESC);

-- El cobro: alguien pide dinero y otro decide si lo paga.
CREATE TABLE bank_charges (
    id           bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

    -- La cuenta que cobra. Es la unica parte obligatoria: siempre se sabe quien recibe.
    to_account   bigint NOT NULL REFERENCES bank_accounts(bank_acc) ON DELETE CASCADE,

    -- A quien se le cobra. NULL es un cobro abierto: lo paga quien lo tenga delante.
    from_account bigint REFERENCES bank_accounts(bank_acc) ON DELETE SET NULL,

    amount       bigint NOT NULL CHECK (amount > 0),
    concept      varchar(120) NOT NULL,

    status       varchar(16) NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending', 'paid', 'cancelled')),

    -- Quien acabo pagando. Puede no ser `from_account` si el cobro era abierto.
    paid_by      bigint REFERENCES bank_accounts(bank_acc) ON DELETE SET NULL,

    created_at   timestamptz NOT NULL DEFAULT now(),
    paid_at      timestamptz,

    -- Un cobro pagado sin pagador, o sin fecha, seria un cobro que nadie puede reclamar.
    CONSTRAINT bank_charges_paid_is_complete CHECK (
        (status <> 'paid') OR (paid_by IS NOT NULL AND paid_at IS NOT NULL)
    )
);

CREATE INDEX bank_charges_to_idx ON bank_charges(to_account, created_at DESC);
CREATE INDEX bank_charges_from_idx ON bank_charges(from_account, created_at DESC)
    WHERE from_account IS NOT NULL;
