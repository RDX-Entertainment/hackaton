-- Port of the state Internet.class.php kept outside the database.
--
-- The legacy leaned on three different places to drive navigation: internet_important was
-- a real table, but the open connection lived in $_SESSION and the history of visited IPs
-- in a serialized browser cookie (history_add). None of that survives a stateless JSON
-- API, so all three become tables.

-- Bookmarks. Direct equivalent of the legacy internet_important.
CREATE TABLE internet_important (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  ip BIGINT NOT NULL,
  UNIQUE (user_id, ip)
);

-- Browsing history. The legacy held five entries in the 'ip-data' cookie and reordered on
-- a revisit; the same semantics survive here as an upsert on visited_at, with the trimming
-- done on read.
CREATE TABLE internet_history (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  ip BIGINT NOT NULL,
  visited_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, ip)
);

-- Access granted on a remote machine, either by the right password (verifyLogin == 1) or
-- through an exploit (verifyLogin == 4). In the legacy this was $_SESSION['LOGGED_IN'] and
-- died with the PHP session; persisted, access survives a refresh and can expire on its own.
CREATE TABLE internet_access (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  ip BIGINT NOT NULL,
  via_exploit BOOLEAN NOT NULL DEFAULT FALSE,
  granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, ip)
);

CREATE INDEX internet_history_recent_idx ON internet_history(user_id, visited_at DESC);
