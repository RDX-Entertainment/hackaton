-- Primera vertical posterior al acceso: edición web, antiforense y análisis.
CREATE TABLE machine_web_revisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_user_id BIGINT NOT NULL,
  target_is_npc BOOLEAN NOT NULL DEFAULT FALSE,
  path VARCHAR(128) NOT NULL,
  content TEXT NOT NULL,
  created_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX machine_web_revisions_target_idx ON machine_web_revisions(target_user_id,target_is_npc,path,created_at DESC);

-- Materializa las páginas que el juego ya sirve. La nueva tabla es el estado editable
-- de la simulación; no toca ningún fichero del servidor ni reemplaza las fuentes previas.
INSERT INTO machine_web_content(target_user_id,target_is_npc,path,content)
SELECT user_id,FALSE,'/index.html',web FROM player_profiles WHERE web <> ''
ON CONFLICT(target_user_id,target_is_npc,path) DO NOTHING;
INSERT INTO machine_web_content(target_user_id,target_is_npc,path,content)
SELECT npc_id,TRUE,'/index.html',web FROM npc_info WHERE web <> ''
ON CONFLICT(target_user_id,target_is_npc,path) DO NOTHING;

INSERT INTO software_domains(code,name) VALUES ('post_access','Post-access') ON CONFLICT(code) DO NOTHING;
INSERT INTO software_capabilities(domain_id,code,name,role,action_kind,relevant_attributes,secondary_attributes,available_actions,max_access_scope,granted_permissions)
SELECT d.id,x.code,x.name,x.role,x.action_kind,x.relevant::jsonb,x.secondary::jsonb,x.actions::jsonb,x.scope,x.permissions::jsonb
FROM software_domains d JOIN (VALUES
 ('web_manipulator','Web manipulator','attacker','modify_web','["manipulation","stability"]','["stealth"]','["modify_web"]','web','["write_files"]'),
 ('forensic_scrubber','Forensic scrubber','attacker','anti_forensics','["anti_forensics","stealth"]','["stability"]','["hide_evidence","forge_evidence"]','user','["modify_logs","forge_logs"]'),
 ('integrity_monitor','Integrity monitor','defender','protect_integrity','["integrity","forensics"]','["resistance"]','["defend_integrity"]','service','[]'),
 ('forensic_analyzer','Forensic analyzer','defender','analyze_evidence','["forensics","detection"]','["integrity"]','["analyze_evidence"]','service','[]')
) AS x(code,name,role,action_kind,relevant,secondary,actions,scope,permissions) ON d.code='post_access'
ON CONFLICT(code) DO NOTHING;

INSERT INTO capability_counters(attacker_capability_id,defender_capability_id)
