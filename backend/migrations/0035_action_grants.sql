-- Quien puede usar cada accion de un sitio.
--
-- Las ordenes de un sitio son de dos familias, y no se conceden igual:
--
--   * las **normales** —enlazar, navegar, cobrar— las usa cualquiera. Una tienda cobra sin
--     ser un banco, y el pago lo atiende el juego con su propio aspecto.
--
--   * las **integradas** llevan la interfaz dentro del HTML del sitio: la pagina pone sus
--     propios campos, el jugador teclea ahi sus credenciales y el juego rellena sus huecos.
--     Eso es un privilegio, porque una pagina que pide un PIN con su propio aspecto es
--     exactamente lo que haria una falsa.
--
-- Quien tiene cada cosa no se decide en el codigo ni maquina por maquina, sino aqui, y con
-- cuatro alcances que cubren lo que hace falta sin llegar al detalle de una IP:
--
--   `all_sites`           todas las webs del juego
--   `all_organizations`   cualquier web que pertenezca a una corporacion
--   `organization`        las webs de una corporacion concreta
--   `site`                una web concreta
--
-- Un `action` de `*` concede la familia entera. Asi, dar la banca a una corporacion nueva es
-- una fila, y no tocar Rust.

CREATE TABLE action_grants (
    id              bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,

    -- El verbo, o `*` para toda la familia indicada.
    action          varchar(40) NOT NULL,

    -- A que familia pertenece lo que se concede. Se guarda para poder conceder `*` sin que
    -- eso signifique «absolutamente todo».
    family          varchar(20) NOT NULL
                    CHECK (family IN ('normal', 'integrated')),

    scope           varchar(20) NOT NULL
                    CHECK (scope IN ('all_sites', 'all_organizations', 'organization', 'site')),

    organization_id bigint REFERENCES organizations(id) ON DELETE CASCADE,
    npc_id          bigint REFERENCES npc(id) ON DELETE CASCADE,

    created_at      timestamptz NOT NULL DEFAULT now(),

    -- Un alcance sin su destino, o con uno que no le toca, seria una concesion que nadie
    -- sabria a quien aplica.
    CONSTRAINT action_grants_target_matches_scope CHECK (
        (scope = 'organization' AND organization_id IS NOT NULL AND npc_id IS NULL)
        OR (scope = 'site' AND npc_id IS NOT NULL AND organization_id IS NULL)
        OR (scope IN ('all_sites', 'all_organizations')
            AND organization_id IS NULL AND npc_id IS NULL)
    )
);

CREATE INDEX action_grants_lookup_idx ON action_grants(family, scope);

-- Lo de siempre, tal como funcionaba hasta ahora: las normales las tiene todo el mundo.
INSERT INTO action_grants(action, family, scope)
VALUES ('*', 'normal', 'all_sites');

-- Y las integradas empiezan concedidas a los bancos, que es donde se probaron. No es una
-- regla del motor: es una fila, y se quita o se amplia desde el panel como cualquier otra.
INSERT INTO action_grants(action, family, scope, organization_id)
SELECT '*', 'integrated', 'organization', b.organization_id
FROM organization_behaviors b
WHERE b.code = 'banking';
