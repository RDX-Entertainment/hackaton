-- Sistema modular de software. `software` conserva la copia jugable y estas tablas
-- describen por que una copia hace lo que hace; asi no se codifica una mecanica por id.
CREATE TABLE software_domains (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(32) NOT NULL UNIQUE,
  name VARCHAR(50) NOT NULL
);

CREATE TABLE software_capabilities (
  id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  domain_id SMALLINT NOT NULL REFERENCES software_domains(id) ON DELETE RESTRICT,
  code VARCHAR(48) NOT NULL UNIQUE,
  name VARCHAR(60) NOT NULL,
  role VARCHAR(12) NOT NULL CHECK (role IN ('attacker','defender','utility')),
  action_kind VARCHAR(20) NOT NULL
);

CREATE TABLE capability_counters (
  attacker_capability_id SMALLINT NOT NULL REFERENCES software_capabilities(id) ON DELETE CASCADE,
  defender_capability_id SMALLINT NOT NULL REFERENCES software_capabilities(id) ON DELETE CASCADE,
  PRIMARY KEY(attacker_capability_id, defender_capability_id)
);

CREATE TABLE research_modules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  capability_id SMALLINT REFERENCES software_capabilities(id) ON DELETE CASCADE,
  code VARCHAR(48) NOT NULL UNIQUE,
  name VARCHAR(60) NOT NULL,
  -- Beneficios y costes. Los valores finales se materializan al compilar una copia.
  effectiveness_delta INTEGER NOT NULL DEFAULT 0,
  stealth_delta INTEGER NOT NULL DEFAULT 0,
  detection_delta INTEGER NOT NULL DEFAULT 0,
  removal_delta INTEGER NOT NULL DEFAULT 0,
  penetration_delta INTEGER NOT NULL DEFAULT 0,
  stability_delta INTEGER NOT NULL DEFAULT 0,
  cpu_delta INTEGER NOT NULL DEFAULT 0,
  ram_delta INTEGER NOT NULL DEFAULT 0,
  net_delta INTEGER NOT NULL DEFAULT 0,
  size_delta INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE user_research_modules (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  module_id BIGINT NOT NULL REFERENCES research_modules(id) ON DELETE CASCADE,
  unlocked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY(user_id, module_id)
);

CREATE TABLE software_blueprints (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name VARCHAR(25) NOT NULL,
  capability_id SMALLINT NOT NULL REFERENCES software_capabilities(id) ON DELETE RESTRICT,
  revision INTEGER NOT NULL DEFAULT 1 CHECK(revision > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(user_id, name, revision)
);

CREATE TABLE blueprint_modules (
  blueprint_id BIGINT NOT NULL REFERENCES software_blueprints(id) ON DELETE CASCADE,
  module_id BIGINT NOT NULL REFERENCES research_modules(id) ON DELETE RESTRICT,
  PRIMARY KEY(blueprint_id, module_id)
);

CREATE TABLE software_profiles (
  software_id BIGINT PRIMARY KEY REFERENCES software(id) ON DELETE CASCADE,
  blueprint_id BIGINT REFERENCES software_blueprints(id) ON DELETE SET NULL,
  origin VARCHAR(16) NOT NULL CHECK(origin IN ('research','loot','legacy')),
  capability_id SMALLINT REFERENCES software_capabilities(id) ON DELETE SET NULL,
  effectiveness INTEGER NOT NULL DEFAULT 50 CHECK(effectiveness BETWEEN 0 AND 100),
  stealth INTEGER NOT NULL DEFAULT 50 CHECK(stealth BETWEEN 0 AND 100),
  detection INTEGER NOT NULL DEFAULT 0 CHECK(detection BETWEEN 0 AND 100),
  removal INTEGER NOT NULL DEFAULT 0 CHECK(removal BETWEEN 0 AND 100),
  penetration INTEGER NOT NULL DEFAULT 0 CHECK(penetration BETWEEN 0 AND 100),
  stability INTEGER NOT NULL DEFAULT 50 CHECK(stability BETWEEN 0 AND 100),
  cpu_need INTEGER NOT NULL DEFAULT 0 CHECK(cpu_need >= 0),
  ram_need INTEGER NOT NULL DEFAULT 0 CHECK(ram_need >= 0),
  net_need INTEGER NOT NULL DEFAULT 0 CHECK(net_need >= 0),
  weight INTEGER NOT NULL DEFAULT 1 CHECK(weight > 0)
);

-- Estado y evidencia para los procesos nuevos. Las filas antiguas se preservan.
ALTER TABLE processes ADD COLUMN status VARCHAR(12) NOT NULL DEFAULT 'queued'
  CHECK(status IN ('queued','running','succeeded','failed','cancelled'));
ALTER TABLE processes ADD COLUMN result_code VARCHAR(48);
ALTER TABLE processes ADD COLUMN result_message TEXT;
ALTER TABLE processes ADD COLUMN resource_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb;
ALTER TABLE processes ADD COLUMN process_payload JSONB NOT NULL DEFAULT '{}'::jsonb;
ALTER TABLE processes ADD COLUMN started_at TIMESTAMPTZ;

UPDATE processes SET status = CASE WHEN completed_at IS NOT NULL THEN 'succeeded' ELSE 'running' END,
  started_at = time_start;

CREATE INDEX software_profiles_capability_idx ON software_profiles(capability_id);
CREATE INDEX software_blueprints_owner_idx ON software_blueprints(user_id, created_at DESC);
CREATE INDEX processes_status_idx ON processes(status, time_end) WHERE completed_at IS NULL;

