-- El mapa de nodos del jugador: dónde está cada equipo y qué está cableado a qué.
--
-- Las redes de organización ya tenían esto —`organization_network_npcs.map_x/y`
-- y `organization_node_links`—, pero solo para los NPC del panel de
-- administración. El jugador veía sus equipos como una pila de fichas, sin
-- forma de decir que dos están en la misma LAN.
--
-- ## Por qué la posición vive en la base y no en el navegador
--
-- Colocar los nodos es trabajo: se hace una vez y tiene que seguir ahí desde
-- otro equipo y en la siguiente sesión. En `localStorage` sería un dibujo que
-- cada navegador recuerda distinto, y dos pestañas del mismo jugador enseñarían
-- mapas que no coinciden.
--
-- ## Qué impone el esquema
--
-- Un cable une dos equipos distintos y **una sola vez**, mirado desde cualquiera
-- de los dos extremos: el índice único va sobre el par ordenado, así que A→B y
-- B→A son el mismo cable y el segundo no entra. Ponerlo aquí y no solo en Rust
-- es lo que impide que dos peticiones a la vez creen el cable dos veces.
--
-- Cuántos cables admite un equipo no cabe en el esquema —son las `net_slots` de
-- la placa que tenga puesta en ese momento, que cambia al desmontarla—, así que
-- ese límite lo aplica el backend.

ALTER TABLE hardware
  ADD COLUMN IF NOT EXISTS map_x integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS map_y integer NOT NULL DEFAULT 0;

COMMENT ON COLUMN hardware.map_x IS
  'Posicion en el mapa de nodos, en pixeles desde la esquina del lienzo.';

-- Los equipos que ya existían nacen en 0,0 y se taparían unos a otros. Se
-- reparten en una rejilla por orden de creación: no es una colocación pensada,
-- pero es una en la que se ven todos y se pueden arrastrar.
WITH ordenados AS (
  SELECT server_id,
         row_number() OVER (PARTITION BY user_id ORDER BY server_id) - 1 AS n
  FROM hardware
)
UPDATE hardware h
SET map_x = 40 + (o.n % 3) * 210,
    map_y = 40 + (o.n / 3) * 130
FROM ordenados o
WHERE h.server_id = o.server_id
  AND h.map_x = 0
  AND h.map_y = 0;

CREATE TABLE IF NOT EXISTS hardware_links (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     bigint NOT NULL,
  from_server bigint NOT NULL REFERENCES hardware(server_id) ON DELETE CASCADE,
  to_server   bigint NOT NULL REFERENCES hardware(server_id) ON DELETE CASCADE,
  created_at  timestamptz NOT NULL DEFAULT now(),

  -- Un equipo no se cablea consigo mismo.
  CONSTRAINT hardware_links_distintos CHECK (from_server <> to_server)
);

-- El par, sin importar el orden en que se creó: A-B y B-A son el mismo cable.
CREATE UNIQUE INDEX IF NOT EXISTS hardware_links_par_idx
  ON hardware_links (least(from_server, to_server), greatest(from_server, to_server));

CREATE INDEX IF NOT EXISTS hardware_links_owner_idx ON hardware_links (user_id);

COMMENT ON TABLE hardware_links IS
  'Cables LAN entre equipos del mismo jugador. El limite por equipo son las net_slots de su placa, y lo aplica el backend.';
