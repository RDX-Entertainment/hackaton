-- Infraestructura de una organizacion.
--
-- Un NPC ya ES un PC remoto completo: tiene IP, contraseña, hardware, software, log,
-- estado de caida y sitio. Esta migracion no crea un segundo tipo de maquina; agrupa esos
-- NPCs en segmentos de red y deja que un NPC pertenezca a un solo segmento.

CREATE TABLE organization_networks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE RESTRICT,
  name VARCHAR(60) NOT NULL,
  zone VARCHAR(12) NOT NULL DEFAULT 'internal'
    CHECK (zone IN ('public', 'dmz', 'internal', 'restricted')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (organization_id, name)
);

CREATE INDEX organization_networks_organization_idx ON organization_networks(organization_id);

-- Un PC solo puede estar en una red: el UNIQUE de npc_id impide que la misma IP aparezca
-- simultaneamente en dos pools. Borrar una red con PCs se rechaza para no volverlos
-- publicos por accidente.
CREATE TABLE organization_network_npcs (
  network_id BIGINT NOT NULL REFERENCES organization_networks(id) ON DELETE RESTRICT,
  npc_id BIGINT NOT NULL UNIQUE REFERENCES npc(id) ON DELETE RESTRICT,
  role VARCHAR(40) NOT NULL DEFAULT 'server',
  PRIMARY KEY (network_id, npc_id)
);

CREATE INDEX organization_network_npcs_network_idx ON organization_network_npcs(network_id);
