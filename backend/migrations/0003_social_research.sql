-- First-party PostgreSQL equivalents of the legacy clan, profile, research,
-- compromised-list and bitcoin wallet domains.
CREATE TABLE player_profiles (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  biography TEXT NOT NULL DEFAULT '',
  visible BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE clans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clan_ip BIGINT NOT NULL UNIQUE,
  name VARCHAR(25) NOT NULL UNIQUE,
  nick VARCHAR(3) NOT NULL UNIQUE,
  description TEXT NOT NULL DEFAULT '',
  slots_total SMALLINT NOT NULL DEFAULT 10 CHECK(slots_total BETWEEN 1 AND 100),
  created_by BIGINT NOT NULL REFERENCES users(id),
  money BIGINT NOT NULL DEFAULT 0,
  power BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE clan_members (
  clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  auth_level SMALLINT NOT NULL DEFAULT 0,
  hierarchy SMALLINT NOT NULL DEFAULT 0,
  member_since TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY(clan_id,user_id)
);
CREATE TABLE clan_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clan_id BIGINT NOT NULL REFERENCES clans(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  message TEXT NOT NULL DEFAULT '',
  asked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(clan_id,user_id)
);
CREATE TABLE research_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  software_id BIGINT NOT NULL DEFAULT 0,
  software_type SMALLINT NOT NULL,
  new_version INTEGER NOT NULL,
  software_name VARCHAR(30) NOT NULL,
  researched_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE compromised_lists (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  ip BIGINT NOT NULL,
  login VARCHAR(15) NOT NULL,
  password VARCHAR(60) NOT NULL,
  hacked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  virus_id BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE bitcoin_wallets (
  address VARCHAR(34) PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  private_key VARCHAR(64) NOT NULL,
  amount NUMERIC(12,7) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
